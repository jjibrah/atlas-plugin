# ───────────────────────── small utilities ─────────────────────────

def now() -> str:
    return dt.datetime.now(dt.timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")


def today() -> str:
    return dt.date.today().isoformat()


def die(msg: str, code: int = 1) -> None:
    print("atlas: " + msg, file=sys.stderr)
    sys.exit(code)


def run(cmd: List[str], cwd: Optional[Path] = None, check: bool = False, timeout: int = 120) -> Tuple[int, str, str]:
    try:
        p = subprocess.run(cmd, cwd=str(cwd) if cwd else None, capture_output=True, text=True, timeout=timeout)
    except FileNotFoundError:
        if check:
            die("command not found: %s" % cmd[0])
        return 127, "", "not found"
    except subprocess.TimeoutExpired:
        if check:
            die("timed out: %s" % " ".join(cmd))
        return 124, "", "timeout"
    if check and p.returncode != 0:
        die("%s failed:\n%s" % (" ".join(cmd), (p.stderr or p.stdout).strip()))
    return p.returncode, p.stdout, p.stderr


def slugify(s: str) -> str:
    s = re.sub(r"[^a-zA-Z0-9]+", "-", s.strip().lower()).strip("-")
    return s[:40] or "project"


def read_json(p: Path, default: Any) -> Any:
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except (FileNotFoundError, json.JSONDecodeError):
        return default


def write_json(p: Path, data: Any) -> None:
    p.parent.mkdir(parents=True, exist_ok=True)
    tmp = p.with_suffix(p.suffix + ".tmp")
    tmp.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    os.replace(tmp, p)


def glob_re(pattern: str) -> "re.Pattern[str]":
    """Glob with ** support → regex (paths use '/')."""
    pat = pattern.strip().lstrip("./")
    out, i = "", 0
    while i < len(pat):
        c = pat[i]
        if pat[i:i + 3] == "**/":
            out += "(?:.*/)?"
            i += 3
        elif pat[i:i + 2] == "**":
            out += ".*"
            i += 2
        elif c == "*":
            out += "[^/]*"
            i += 1
        elif c == "?":
            out += "[^/]"
            i += 1
        else:
            out += re.escape(c)
            i += 1
    if not any(ch in pattern for ch in "*?") and not pattern.endswith((".py", ".ts", ".js")):
        out += "(?:/.*)?"  # a bare folder matches everything under it
    return re.compile("^" + out + "$")


