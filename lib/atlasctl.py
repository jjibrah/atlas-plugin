def load_config() -> Dict[str, Any]:
    cfg = read_json(CONFIG, None)
    if cfg is None:
        die("not set up on this device. Run: python3 %s setup --mode folder --path <projects folder>  "
            "(or --mode github)" % (LIB / "atlasctl.py"))
    return cfg


def save_config(cfg: Dict[str, Any]) -> None:
    write_json(CONFIG, cfg)


def registry_dir(cfg: Dict[str, Any]) -> Path:
    return Path(cfg["projects_root"]) if cfg["mode"] == "folder" else HOME / "registry"


def load_registry(cfg: Dict[str, Any]) -> Dict[str, Any]:
    return read_json(registry_dir(cfg) / "registry.json", {"next": 1, "projects": []})


def save_registry(cfg: Dict[str, Any], reg: Dict[str, Any], message: str) -> None:
    d = registry_dir(cfg)
    write_json(d / "registry.json", reg)
    lines = ["# ATLAS projects", "", "Generated by atlasctl — do not edit.", "",
             "| ID | Project | Client | Created | Storage |", "|---|---|---|---|---|"]
    for p in reg["projects"]:
        lines.append("| %s | %s | %s | %s | %s |" % (p["id"], p["name"], p.get("client", ""), p.get("created", ""),
                                                   p.get("remote") or p["dir"]))
    (d / "REGISTRY.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    if cfg["mode"] == "github":
        git_commit_push(d, message)


def project_dir_for(cfg: Dict[str, Any], entry: Dict[str, Any]) -> Path:
    if cfg["mode"] == "folder":
        return Path(cfg["projects_root"]) / entry["dir"]
    return Path(cfg.get("local_root", str(HOME / "projects"))) / entry["dir"]


# ───────────────────────── git helpers ─────────────────────────

def is_git(d: Path) -> bool:
    return (d / ".git").exists()


def has_remote(d: Path) -> bool:
    rc, out, _ = run(["git", "remote"], cwd=d)
    return rc == 0 and bool(out.strip())


def git_pull(d: Path) -> None:
    if is_git(d) and has_remote(d):
        rc, out, err = run(["git", "pull", "--rebase", "--autostash", "-q"], cwd=d, timeout=120)
        if rc != 0:
            print("atlas: warning — could not pull %s: %s" % (d.name, (err or out).strip()[:200]), file=sys.stderr)


def git_commit_push(d: Path, message: str, push: bool = True) -> None:
    if not is_git(d):
        return
    run(["git", "add", "-A"], cwd=d)
    rc, out, _ = run(["git", "status", "--porcelain"], cwd=d)
    if out.strip():
        run(["git", "commit", "-q", "-m", message], cwd=d)
    if push and has_remote(d):
        rc, out, err = run(["git", "push", "-q"], cwd=d, timeout=120)
        if rc != 0:
            git_pull(d)
            rc, out, err = run(["git", "push", "-q"], cwd=d, timeout=120)
            if rc != 0:
                print("atlas: warning — push failed for %s: %s" % (d.name, (err or out).strip()[:200]), file=sys.stderr)


def gh_ok() -> bool:
    rc, _, _ = run(["gh", "auth", "status"], timeout=20)
    return rc == 0


# ───────────────────────── project resolution ─────────────────────────

class Project:
    def __init__(self, path: Path, cfg: Dict[str, Any]):
        self.path = path
        self.cfg = cfg
        self.meta = read_json(path / "atlas.json", None)
        if self.meta is None:
            die("%s is not an ATLAS project (no atlas.json)" % path)

    @property
    def id(self) -> str:
        return self.meta["id"]

    @property
    def events_file(self) -> Path:
        return self.path / "log" / "events.jsonl"

    def events(self) -> List[Dict[str, Any]]:
        out = []
        try:
            with self.events_file.open(encoding="utf-8") as f:
                for ln in f:
                    ln = ln.strip()
                    if ln:
                        try:
                            out.append(json.loads(ln))
                        except json.JSONDecodeError:
                            out.append({"type": "corrupt", "raw": ln})
        except FileNotFoundError:
            pass
        return out

    def repo_paths(self) -> Dict[str, Path]:
        links = self.cfg.get("repo_paths", {}).get(self.id, {})
        out = {}
        for r in self.meta.get("repos", []):
            name = r["name"]
            if name in links and Path(links[name]).exists():
                out[name] = Path(links[name])
            elif r.get("path") and Path(r["path"]).exists():
                out[name] = Path(r["path"])
            elif r.get("url"):
                local = HOME / "repos" / self.id / name
                if not local.exists():
                    local.parent.mkdir(parents=True, exist_ok=True)
                    rc, _, err = run(["git", "clone", "-q", r["url"], str(local)], timeout=600)
                    if rc != 0:
                        print("atlas: warning — cannot clone %s: %s" % (r["url"], err.strip()[:200]), file=sys.stderr)
                        continue
                out[name] = local
        return out

    def sync_pull(self) -> None:
        if self.cfg["mode"] == "github":
            git_pull(self.path)
            repair_if_needed(self)

    def sync_push(self, message: str) -> None:
        git_commit_push(self.path, message, push=self.cfg["mode"] == "github")


def find_project(cfg: Dict[str, Any], ref: Optional[str]) -> Project:
    reg = load_registry(cfg)
    if ref:
        ref_u = ref.upper()
        for e in reg["projects"]:
            if e["id"] == ref_u or e["dir"] == ref or e["name"].lower() == ref.lower():
                d = project_dir_for(cfg, e)
                if not d.exists() and cfg["mode"] == "github" and e.get("remote"):
                    d.parent.mkdir(parents=True, exist_ok=True)
                    run(["git", "clone", "-q", e["remote"], str(d)], check=True, timeout=600)
                return Project(d, cfg)
        die("no project %r. Known: %s" % (ref, ", ".join(e["id"] for e in reg["projects"]) or "none"))
    cwd = Path.cwd().resolve()
    for d in [cwd] + list(cwd.parents):
        if (d / "atlas.json").exists():
            return Project(d, cfg)
    for pid, names in cfg.get("repo_paths", {}).items():
        for p in names.values():
            try:
                cwd.relative_to(Path(p).resolve())
                return find_project(cfg, pid)
            except ValueError:
                pass
    cur = cfg.get("current")
    if cur:
        return find_project(cfg, cur)
    die("no current project. Use --project PRJ-xxxx, `atlasctl use PRJ-xxxx`, or `atlasctl new`.")
    raise SystemExit  # for type checkers


# ───────────────────────── event log ─────────────────────────

class Lock:
    def __init__(self, project: Project):
        self.file = project.path / "state" / "lock"
        self.device = project.cfg.get("device", "?")

    def __enter__(self) -> "Lock":
        self.file.parent.mkdir(parents=True, exist_ok=True)
        for _ in range(50):
            try:
                fd = os.open(str(self.file), os.O_CREAT | os.O_EXCL | os.O_WRONLY)
                os.write(fd, json.dumps({"device": self.device, "pid": os.getpid(),
                                         "until": time.time() + LOCK_SECONDS}).encode())
                os.close(fd)
                return self
            except FileExistsError:
                info = read_json(self.file, {})
                if info.get("until", 0) < time.time():
                    try:
                        self.file.unlink()
                    except FileNotFoundError:
                        pass
                    continue
                time.sleep(0.1)
        die("project is locked by device %s (another run in progress). If that run crashed, delete %s"
            % (read_json(self.file, {}).get("device", "?"), self.file))
        return self

    def __exit__(self, *a: Any) -> None:
        try:
            self.file.unlink()
        except FileNotFoundError:
            pass


def event_hash(prev: str, ev: Dict[str, Any]) -> str:
    body = {k: v for k, v in ev.items() if k != "hash"}
    body["prev"] = prev
    return hashlib.sha256(json.dumps(body, sort_keys=True, ensure_ascii=False).encode()).hexdigest()


def append_event(project: Project, etype: str, actor: str, summary: str, refs: Optional[List[str]] = None,
                 data: Optional[Dict[str, Any]] = None, by: str = "agent") -> Dict[str, Any]:
    with Lock(project):
        evs = project.events()
        last = evs[-1] if evs else {}
        ev = {"seq": (last.get("seq", 0) + 1) if evs else 1, "ts": now(), "device": project.cfg.get("device", "?"),
              "actor": actor, "by": by, "type": etype, "refs": refs or [], "summary": summary, "data": data or {},
              "prev": last.get("hash", "")}
        ev["hash"] = event_hash(ev["prev"], ev)
        project.events_file.parent.mkdir(parents=True, exist_ok=True)
        with project.events_file.open("a", encoding="utf-8") as f:
            f.write(json.dumps(ev, ensure_ascii=False) + "\n")
    return ev


def verify_chain(evs: List[Dict[str, Any]]) -> List[str]:
    problems, prev = [], ""
    for i, ev in enumerate(evs):
        if ev.get("type") == "corrupt":
            problems.append("line %d is not valid JSON" % (i + 1))
            continue
        if ev.get("prev", "") != prev:
            problems.append("seq %s: chain break (prev hash does not match line %d)" % (ev.get("seq"), i))
        if event_hash(ev.get("prev", ""), ev) != ev.get("hash"):
            problems.append("seq %s: content changed after it was written" % ev.get("seq"))
        if ev.get("seq") != i + 1:
            problems.append("seq %s at line %d: out of order" % (ev.get("seq"), i + 1))
        prev = ev.get("hash", "")
    return problems


def repair_if_needed(project: Project, force: bool = False) -> bool:
    """After a sync merge (git union merge of two devices' appends) re-order by time and re-chain.
    Only re-chains when every event's own content hash is intact; tampering is never 'repaired'."""
    evs = project.events()
    if not evs:
        return False
    problems = verify_chain(evs)
    if not problems and not force:
        return False
    tampered = [e for e in evs if e.get("type") == "corrupt" or event_hash(e.get("prev", ""), e) != e.get("hash")]
    if tampered:
        print("atlas: WARNING — %d event(s) were edited after being written; not repairing. Run `atlasctl verify-log`."
              % len(tampered), file=sys.stderr)
        return False
    seen, uniq = set(), []
    for e in sorted(evs, key=lambda e: (e["ts"], e.get("device", ""), e["seq"])):
        if e["hash"] in seen:
            continue
        seen.add(e["hash"])
        uniq.append(e)
    prev = ""
    with Lock(project):
        out = []
        for i, e in enumerate(uniq):
            e = dict(e)
            e["orig"] = {"seq": e["seq"], "hash": e["hash"]} if "orig" not in e else e["orig"]
            e["seq"] = i + 1
            e["prev"] = prev
            e["hash"] = event_hash(prev, e)
            prev = e["hash"]
            out.append(e)
        tmp = project.events_file.with_suffix(".tmp")
        tmp.write_text("".join(json.dumps(e, ensure_ascii=False) + "\n" for e in out), encoding="utf-8")
        os.replace(tmp, project.events_file)
    append_event(project, "log.merged", "atlas", "Merged event logs from %d devices; re-chained %d events"
                 % (len({e.get("device") for e in uniq}), len(uniq)))
    return True


