def cmd_setup(a: argparse.Namespace) -> None:
    HOME.mkdir(parents=True, exist_ok=True)
    cfg = read_json(CONFIG, {}) or {}
    cfg.setdefault("device", "%s-%s" % (socket.gethostname().split(".")[0][:20], uuid.uuid4().hex[:6]))
    mode = a.mode or cfg.get("mode")
    if mode not in ("folder", "github"):
        die("choose --mode folder --path <folder>  or  --mode github [--owner <user-or-org>]")
    cfg["mode"] = mode
    if mode == "folder":
        root = Path(a.path or cfg.get("projects_root") or "").expanduser()
        if not str(root) or str(root) == ".":
            die("folder mode needs --path <where your projects live>")
        root = root.resolve()
        root.mkdir(parents=True, exist_ok=True)
        cfg["projects_root"] = str(root)
        if not (root / "registry.json").exists():
            write_json(root / "registry.json", {"next": 1, "projects": []})
        print("Folder mode: projects live in %s" % root)
    else:
        if not shutil.which("gh"):
            die("GitHub mode needs the GitHub CLI (gh). Install it, run `gh auth login`, then re-run setup.")
        if not gh_ok():
            die("GitHub CLI is not logged in. Run `gh auth login` yourself, then re-run setup.")
        owner = a.owner or cfg.get("owner")
        if not owner:
            owner = run(["gh", "api", "user", "--jq", ".login"], check=True)[1].strip()
        cfg["owner"] = owner
        cfg["local_root"] = str(Path(a.path).expanduser().resolve()) if a.path else cfg.get(
            "local_root", str(HOME / "projects"))
        Path(cfg["local_root"]).mkdir(parents=True, exist_ok=True)
        regdir = HOME / "registry"
        name = "%s/atlas-registry" % owner
        if not regdir.exists():
            if run(["gh", "repo", "view", name], timeout=30)[0] != 0:
                run(["gh", "repo", "create", name, "--private", "--description", "ATLAS project registry"],
                    check=True, timeout=60)
            rc, _, err = run(["gh", "repo", "clone", name, str(regdir)], timeout=120)
            if rc != 0:
                die("could not clone %s: %s" % (name, err))
        if not (regdir / "registry.json").exists():
            write_json(regdir / "registry.json", {"next": 1, "projects": []})
            git_commit_push(regdir, "Initialise ATLAS registry")
        else:
            git_pull(regdir)
        print("GitHub mode: owner %s · registry %s · local clones in %s" % (owner, name, cfg["local_root"]))
    save_config(cfg)
    install_shim()
    if not a.no_deps:
        deps_report(install=True)


def install_shim() -> None:
    """Install an `atlas` terminal command that always runs the newest installed copy of this plugin."""
    (HOME / "bin").mkdir(parents=True, exist_ok=True)
    (HOME / "lib_path").write_text(str(LIB), encoding="utf-8")
    shim = HOME / "bin" / "atlas"
    shim.write_text('#!/bin/sh\nexec python3 "$(cat "${ATLAS_HOME:-$HOME/.atlas}/lib_path")/atlasctl.py" "$@"\n',
                    encoding="utf-8")
    shim.chmod(0o755)
    if os.environ.get("ATLAS_HOME"):
        return                                  # a test home: do not touch the user's PATH folders
    target = Path.home() / ".local" / "bin" / "atlas"
    try:
        target.parent.mkdir(parents=True, exist_ok=True)
        if target.is_symlink() or target.exists():
            target.unlink()
        target.symlink_to(shim)
        on_path = str(target.parent) in os.environ.get("PATH", "").split(os.pathsep)
        print("Terminal command installed: %s%s" % (target, "" if on_path else
              '  (add ~/.local/bin to your PATH to type `atlas status` anywhere)'))
    except OSError as e:
        print("Could not link the `atlas` command into ~/.local/bin (%s); use %s" % (e, shim))


def deps_report(install: bool = False) -> None:
    venv = HOME / "venv"
    py = venv / "bin" / "python"
    if install and not py.exists():
        print("Creating %s (PDF reading)…" % venv)
        rc, _, err = run([sys.executable, "-m", "venv", str(venv)], timeout=300)
        if rc != 0:
            print("  could not create the venv: %s" % err.strip()[:200])
    if install and py.exists():
        rc, _, err = run([str(py), "-m", "pip", "install", "-q", "--upgrade", "pymupdf"], timeout=900)
        print("  python packages: %s" % ("ok" if rc == 0 else "FAILED — " + err.strip()[-300:]))
    from pdf_export import find_browser  # noqa: E402
    checks = [("git", bool(shutil.which("git"))), ("GitHub CLI (gh)", bool(shutil.which("gh"))),
              ("venv (PDF reading)", py.exists()),
              ("Chrome/Edge/Chromium for PDF export", bool(find_browser()))]
    for name, ok in checks:
        print("  %-40s %s" % (name, "ok" if ok else "missing"))


