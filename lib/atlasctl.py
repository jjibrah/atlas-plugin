def id_graph(p: Project) -> Tuple[Dict[str, set], Dict[str, str]]:
    """Edges id -> set(ids it links to) from every table row in project documents; where each id is defined."""
    links: Dict[str, set] = {}
    where: Dict[str, str] = {}
    files = []
    for sub in ("discovery", "design", "plan", "test"):
        for f in sorted((p.path / sub).rglob("*.md")):
            if "/sources/" in str(f) or "/meetings/" in str(f):
                continue
            files.append(f)
    for f in files:
        rel = str(f.relative_to(p.path))
        in_discovery = rel.startswith("discovery")
        for t in md.read_tables(f):
            for r in t.rows:
                if not r:
                    continue
                own = md.ids_in(r[0])
                if len(own) != 1:
                    continue
                me = own[0]
                if in_discovery and re.match(r"^M\d+$", me):
                    continue
                where.setdefault(me, rel)
                others = set(md.expand_ranges(" ".join(r[1:]))) - {me}
                others = {o for o in others if not md.WEAK_LINK.match(o) or (o.startswith("M") and not in_discovery)}
                links.setdefault(me, set()).update(others)
    return links, where


def cmd_impact(a: argparse.Namespace) -> None:
    cfg = load_config()
    p = find_project(cfg, a.project)
    links, where = id_graph(p)
    rev: Dict[str, set] = {}
    for src, dsts in links.items():
        for d in dsts:
            rev.setdefault(d, set()).add(src)
    start = [x.upper() for x in a.ids]
    seen, frontier = set(start), list(start)
    while frontier:
        x = frontier.pop()
        for y in rev.get(x, ()):
            if y not in seen:
                seen.add(y)
                frontier.append(y)
    affected = sorted(seen - set(start), key=lambda i: (re.sub(r"\d", "", i), i))
    unknown = [s for s in start if s not in where and s not in rev]
    if unknown:
        print("Not found in project documents: %s" % ", ".join(unknown))
    if not affected:
        print("Nothing downstream of %s." % ", ".join(start))
        return
    groups: Dict[str, List[str]] = {}
    for i in affected:
        groups.setdefault(re.sub(r"-?\d+$", "", i), []).append(i)
    print("Downstream of %s (%d items):" % (", ".join(start), len(affected)))
    for k in sorted(groups):
        print("  %-5s %s" % (k, ", ".join("%s (%s)" % (i, where.get(i, "?")) for i in groups[k])))
    if a.cr:
        append_event(p, "cr.impact", "atlas", "%s impact: %d item(s) downstream of %s" % (a.cr, len(affected),
                                                                                         ", ".join(start)),
                     refs=[a.cr] + start, data={"cr": a.cr, "touches": start, "affected": affected})
        p.sync_push("%s impact" % a.cr)


def cmd_gate(a: argparse.Namespace) -> None:
    cfg = load_config()
    p = find_project(cfg, a.project)
    g = a.gate.upper()
    if g not in ("G1", "G2", "G3", "G4", "G5"):
        die("gate must be G1–G5")
    if g in ("G4", "G5") and not a.phase:
        _, wps = read_plan(p)
        st = build_status(p)
        a.phase = st["current_phase"]
        if not a.phase:
            die("%s is per phase: add --phase P1" % g)
    data = {"gate": g, "phase": a.phase or ""}
    if a.waive:
        append_event(p, "gate.waived", "spartan", "%s%s waived: %s" % (g, ("/" + a.phase) if a.phase else "", a.waive),
                     refs=[g], data={**data, "reason": a.waive}, by="user")
        p.sync_push("Waive %s" % g)
        print("%s waived and logged." % g)
        return
    import gates as gates_mod  # noqa: E402
    if g == "G4" and not a.no_reconcile:
        cmd_reconcile(p, quiet=True)
    given = dict(x.split("=", 1) for x in (a.answer or []) if "=" in x)
    if given:
        append_event(p, "gate.answer", "atlas", "%s answered: %s" % (g, ", ".join("%s=%s" % kv for kv in given.items())),
                     refs=[g], data={**data, "answers": given}, by="user")
    answers = saved_answers(p, g, a.phase)
    results = gates_mod.run_gate(p, g, a.phase, answers=answers)
    fails = [r for r in results if r["result"] == "fail"]
    asks = [r for r in results if r["result"] == "ask"]
    for r in results:
        if r["result"] in ("pass", "n/a") and not a.all:
            continue
        mark = {"pass": "PASS", "fail": "FAIL", "ask": "ASK ", "n/a": "n/a "}[r["result"]]
        print("[%s] %s%s" % (mark, r["check"], (" — " + r["detail"]) if r["detail"] else ""))
    verdict = "failed" if fails else ("pending" if asks else "passed")
    print("%s%s: %s (%d pass, %d fail, %d need an answer)" % (g, ("/" + a.phase) if a.phase else "", verdict.upper(),
                                                             sum(r["result"] == "pass" for r in results), len(fails),
                                                             len(asks)))
    if asks:
        print("Answer with: atlasctl gate %s%s --answer <key>=yes|no …  (keys: %s)" % (
            g, (" --phase " + a.phase) if a.phase else "", ", ".join(r["key"] for r in asks)))
    already = gate_state(p.events()).get(g + (("/" + a.phase) if a.phase else ""), {}).get("result")
    if (a.record and verdict != "pending") or (verdict == "passed" and already != "passed"):
        append_event(p, "gate." + verdict, "spartan", "%s%s %s: %d checks, %d failed" % (
            g, ("/" + a.phase) if a.phase else "", verdict, len(results), len(fails)), refs=[g],
            data={**data, "results": results})
        write_views(p, build_status(p))
        p.sync_push("Gate %s %s" % (g, verdict))
        print("Recorded.")
    if verdict != "passed":
        sys.exit(2)


