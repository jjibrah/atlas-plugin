def read_modules(project: Project) -> List[Dict[str, Any]]:
    out = []
    for t in md.read_tables(project.path / "design" / "MODULES.md"):
        ci = t.col("module")
        if ci is None or t.col("rigour", "rigor") is None:
            continue
        cn, cr, cp = t.col("name"), t.col("rigour", "rigor"), t.col("paths", "path")
        for r in t.rows:
            mid = (r[ci] if ci < len(r) else "").strip("* ")
            if not re.match(r"^M\d+$", mid):
                continue
            g = lambda i: (r[i].strip() if i is not None and i < len(r) else "")  # noqa: E731
            paths = [p.strip().strip("`") for p in g(cp).split(",") if p.strip().strip("`") not in ("", "?", "-", "—")]
            out.append({"id": mid, "name": g(cn), "proposed": g(cr).strip("* ").capitalize(), "paths": paths})
    confirmed = {}
    for ev in project.events():
        if ev.get("type") == "rigour.set":
            confirmed[ev["data"].get("module")] = ev["data"]
    for m in out:
        c = confirmed.get(m["id"])
        m["rigour"] = c["level"] if c else (m["proposed"] if m["proposed"] in LEVELS else default_level(project))
        m["confirmed"] = bool(c)
    return out


def track(project: Project) -> str:
    """'small' projects run a shorter pipeline (design and plan in one run); everything else is 'standard'."""
    t = project.meta.get("track")
    if t in ("small", "standard"):
        return t
    return "small" if project.meta.get("size") == "Small" else "standard"


