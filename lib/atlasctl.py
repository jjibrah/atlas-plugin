def cmd_handover_data(a: argparse.Namespace) -> None:
    """Facts for Alice's handover/report: compact JSON."""
    cfg = load_config()
    p = find_project(cfg, a.project)
    s = build_status(p)
    evs = p.events()
    keep = ("signoff.recorded", "decision.recorded", "gate.passed", "gate.waived", "gate.failed", "phase.released",
            "cr.opened", "cr.approved", "cr.done", "cr.rejected", "rigour.set", "doc.version", "blueprint.published",
            "report.sent")
    print(json.dumps({"project": p.meta, "next": s["next"], "attention": s["attention"], "stages": s["stages"],
                      "phases": s["phases"], "released": s["released"],
                      "work_packages": [{k: w[k] for k in ("id", "title", "phase", "state", "confidence", "level")}
                                        for w in s["wps"]],
                      "modules": [{k: m[k] for k in ("id", "name", "rigour", "confirmed")} for m in s["modules"]],
                      "change_requests": s["crs"], "questions_open": s["questions"][0],
                      "milestones": [{k: ev.get(k) for k in ("seq", "ts", "type", "summary", "refs")}
                                     for ev in evs if ev.get("type") in keep]}, default=str))


